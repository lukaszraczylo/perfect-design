import { afterEach, describe, expect, it } from 'vitest'
import { nextTick } from 'vue'
import { EDGES, NODES, content, dragTo, edgeEl, edgesProp, flush, mountCanvas, nodeEl, nodesProp, pointer, portEl, selected, status, svgOf, unmountAll, viewport } from './testing'

afterEach(unmountAll)

const x = (w: ReturnType<typeof mountCanvas>, id: string) => nodesProp(w).find((n) => n.id === id)!
const getVp = (w: ReturnType<typeof mountCanvas>) => (w.vm as unknown as { getViewport: () => { x: number; y: number; zoom: number } }).getViewport()
const setVp = (w: ReturnType<typeof mountCanvas>, v: object) => (w.vm as unknown as { setViewport: (v: object) => void }).setViewport(v)
const button = (w: ReturnType<typeof mountCanvas>, text: string) => w.findAll('[data-slot="flow-canvas-toolbar"] button').find((b) => (b.attributes('aria-label') ?? b.text()) === text)!

describe('selection with the pointer', () => {
  it('selects a node on press, announces nothing, emits select, and focuses it', async () => {
    const w = mountCanvas()
    pointer(nodeEl(w, 'b'), 'pointerdown', { clientX: 310, clientY: 10 })
    pointer(svgOf(w), 'pointerup', { clientX: 310, clientY: 10 })
    await nextTick()
    expect(selected(w)).toEqual(['b'])
    expect(nodeEl(w, 'b').getAttribute('aria-pressed')).toBe('true')
    expect(document.activeElement).toBe(nodeEl(w, 'b'))
    expect(w.emitted('select')!.at(-1)).toEqual([{ nodes: ['b'], edges: [] }])
    expect(nodeEl(w, 'b').parentElement!.querySelector('[data-slot="flow-canvas-node-selection"]')).not.toBeNull()
  })
  it('replaces the selection on a plain press and toggles with shift, ctrl or meta', async () => {
    const w = mountCanvas()
    const press = async (id: string, init: PointerEventInit = {}) => {
      pointer(nodeEl(w, id), 'pointerdown', { clientX: 5, clientY: 5, ...init })
      pointer(svgOf(w), 'pointerup', { clientX: 5, clientY: 5 })
      await nextTick()
    }
    await press('a')
    await press('b', { shiftKey: true })
    expect(selected(w).sort()).toEqual(['a', 'b'])
    await press('c', { ctrlKey: true })
    expect(selected(w).sort()).toEqual(['a', 'b', 'c'])
    await press('a', { metaKey: true })
    expect(selected(w).sort()).toEqual(['b', 'c'])
    await press('b', { shiftKey: true })
    expect(selected(w)).toEqual(['c'])
    await press('a')
    expect(selected(w)).toEqual(['a'])
  })
  it('keeps a multi-selection when pressing a selected node to drag, and collapses on a plain click', async () => {
    const w = mountCanvas()
    for (const id of ['a', 'b']) {
      pointer(nodeEl(w, id), 'pointerdown', { clientX: 5, clientY: 5, shiftKey: true })
      pointer(svgOf(w), 'pointerup', { clientX: 5, clientY: 5 })
    }
    await nextTick()
    pointer(nodeEl(w, 'a'), 'pointerdown', { clientX: 5, clientY: 5 })
    expect(selected(w).sort()).toEqual(['a', 'b'])
    pointer(svgOf(w), 'pointerup', { clientX: 5, clientY: 5 })
    await nextTick()
    expect(selected(w)).toEqual(['a'])
  })
  it('clears the selection with a click on the background but not after a pan', async () => {
    const w = mountCanvas()
    pointer(nodeEl(w, 'a'), 'pointerdown', { clientX: 5, clientY: 5 })
    pointer(svgOf(w), 'pointerup', { clientX: 5, clientY: 5 })
    await nextTick()
    await dragTo(svgOf(w), svgOf(w), [500, 400], [560, 440])
    expect(selected(w)).toEqual(['a'])
    await dragTo(svgOf(w), svgOf(w), [500, 400])
    expect(selected(w)).toEqual([])
    expect(w.emitted('select')!.at(-1)).toEqual([{ nodes: [], edges: [] }])
  })
  it('a shift click on the background keeps the selection', async () => {
    const w = mountCanvas()
    pointer(nodeEl(w, 'a'), 'pointerdown', { clientX: 5, clientY: 5 })
    pointer(svgOf(w), 'pointerup', { clientX: 5, clientY: 5 })
    pointer(svgOf(w), 'pointerdown', { clientX: 600, clientY: 400, ctrlKey: true })
    pointer(svgOf(w), 'pointerup', { clientX: 600, clientY: 400 })
    await nextTick()
    expect(selected(w)).toEqual(['a'])
  })
  it('selects an edge, toggles it with shift and does not emit when nothing changes', async () => {
    const w = mountCanvas({ edges: [...EDGES(), { id: 'e2', from: 'a', to: 'c' }] })
    pointer(edgeEl(w, 'e1'), 'pointerdown', { clientX: 200, clientY: 26 })
    await nextTick()
    expect(edgeEl(w, 'e1').getAttribute('aria-pressed')).toBe('true')
    expect(edgeEl(w, 'e1').querySelector('[data-slot="flow-canvas-edge-line"]')!.getAttribute('stroke-width')).toBe('3')
    expect(edgeEl(w, 'e2').querySelector('[data-slot="flow-canvas-edge-line"]')!.getAttribute('stroke-width')).toBe('1.5')
    expect(w.emitted('select')!.at(-1)).toEqual([{ nodes: [], edges: ['e1'] }])
    pointer(edgeEl(w, 'e2'), 'pointerdown', { clientX: 50, clientY: 100, shiftKey: true })
    expect(w.emitted('select')!.at(-1)).toEqual([{ nodes: [], edges: ['e1', 'e2'] }])
    pointer(edgeEl(w, 'e1'), 'pointerdown', { clientX: 50, clientY: 100, shiftKey: true })
    expect(w.emitted('select')!.at(-1)).toEqual([{ nodes: [], edges: ['e2'] }])
    const n = w.emitted('select')!.length
    pointer(edgeEl(w, 'e2'), 'pointerdown', { clientX: 50, clientY: 100 })
    expect(w.emitted('select')!.length).toBe(n)
  })
  it('selects by a click that does not come from a pointer (screen reader activation)', async () => {
    const w = mountCanvas()
    nodeEl(w, 'c').dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 0 }))
    nodeEl(w, 'a').dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 0, shiftKey: true }))
    edgeEl(w, 'e1').dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 0 }))
    await nextTick()
    expect(selected(w)).toEqual([])
    expect(edgeEl(w, 'e1').getAttribute('aria-pressed')).toBe('true')
    nodeEl(w, 'c').dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 0 }))
    nodeEl(w, 'a').dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 0, ctrlKey: true }))
    await nextTick()
    expect(selected(w).sort()).toEqual(['a', 'c'])
  })
  it('ignores a pointer click (detail 1) in the click handler, which the pointer path already handled', async () => {
    const w = mountCanvas()
    nodeEl(w, 'c').dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 1 }))
    await nextTick()
    expect(selected(w)).toEqual([])
  })
  it('drops selected ids that disappear from the data', async () => {
    const w = mountCanvas()
    pointer(nodeEl(w, 'a'), 'pointerdown', { clientX: 5, clientY: 5 })
    pointer(svgOf(w), 'pointerup', { clientX: 5, clientY: 5 })
    pointer(edgeEl(w, 'e1'), 'pointerdown', { clientX: 5, clientY: 5, shiftKey: true })
    await nextTick()
    await w.setProps({ nodes: NODES().filter((n) => n.id !== 'a'), edges: [] })
    expect(selected(w)).toEqual([])
    expect(w.emitted('select')!.at(-1)).toEqual([{ nodes: [], edges: [] }])
  })
  it('ignores non-primary mouse buttons', async () => {
    const w = mountCanvas()
    pointer(nodeEl(w, 'a'), 'pointerdown', { clientX: 5, clientY: 5, button: 2 })
    await nextTick()
    expect(selected(w)).toEqual([])
  })
})

describe('moving nodes with the pointer', () => {
  it('drags a node, commits once on release and emits node-move, update:nodes and change', async () => {
    const w = mountCanvas()
    pointer(nodeEl(w, 'a'), 'pointerdown', { clientX: 10, clientY: 10 })
    pointer(svgOf(w), 'pointermove', { clientX: 60, clientY: 40 })
    await nextTick()
    // live position while dragging, model untouched
    expect(nodeEl(w, 'a').parentElement!.getAttribute('transform')).toBe('translate(50 30)')
    expect(x(w, 'a')).toMatchObject({ x: 0, y: 0 })
    pointer(svgOf(w), 'pointermove', { clientX: 110, clientY: 60 })
    pointer(svgOf(w), 'pointerup', { clientX: 110, clientY: 60 })
    await nextTick()
    expect(x(w, 'a')).toMatchObject({ x: 100, y: 50, label: 'Alpha' })
    expect(x(w, 'b')).toMatchObject({ x: 300, y: 0 })
    expect(w.emitted('node-move')).toEqual([[{ nodes: [{ id: 'a', x: 100, y: 50 }] }]])
    expect(w.emitted('change')!.at(-1)![0]).toMatchObject({ reason: 'move' })
    expect(w.emitted('update:nodes')).toHaveLength(1)
    expect(nodeEl(w, 'a').parentElement!.getAttribute('transform')).toBe('translate(100 50)')
  })
  it('does not move below the movement threshold and emits nothing', async () => {
    const w = mountCanvas()
    await dragTo(nodeEl(w, 'a'), svgOf(w), [10, 10], [11, 11], [12, 10])
    expect(w.emitted('node-move')).toBeUndefined()
    expect(x(w, 'a')).toMatchObject({ x: 0, y: 0 })
    expect(selected(w)).toEqual(['a'])
  })
  it('snaps to the grid and keeps relative offsets of a multi-selection', async () => {
    const w = mountCanvas({ grid: 20, nodes: [{ id: 'a', x: 3, y: 3 }, { id: 'b', x: 303, y: 13 }] , edges: [] })
    pointer(nodeEl(w, 'b'), 'pointerdown', { clientX: 310, clientY: 20, shiftKey: true })
    pointer(nodeEl(w, 'a'), 'pointerdown', { clientX: 10, clientY: 10, shiftKey: true })
    pointer(svgOf(w), 'pointerup', {})
    await nextTick()
    await dragTo(nodeEl(w, 'a'), svgOf(w), [10, 10], [47, 38])
    expect(selected(w).sort()).toEqual(['a', 'b'])
    expect(x(w, 'a')).toMatchObject({ x: 40, y: 40 })
    expect(x(w, 'b')).toMatchObject({ x: 340, y: 50 })
    expect((w.emitted('node-move')!.at(-1)![0] as { nodes: { id: string }[] }).nodes.map((n) => n.id).sort()).toEqual(['a', 'b'])
  })
  it('accepts grid=true as 20 and ignores nonsense', async () => {
    const w = mountCanvas({ grid: true })
    await dragTo(nodeEl(w, 'a'), svgOf(w), [10, 10], [47, 10])
    expect(x(w, 'a').x).toBe(40)
    const bad = mountCanvas({ grid: -5 })
    await dragTo(nodeEl(bad, 'a'), svgOf(bad), [10, 10], [37, 10])
    expect(x(bad, 'a').x).toBe(27)
  })
  it('divides the pointer distance by the zoom', async () => {
    const w = mountCanvas()
    setVp(w, { zoom: 2 })
    await nextTick()
    await dragTo(nodeEl(w, 'a'), svgOf(w), [10, 10], [110, 60])
    expect(x(w, 'a')).toMatchObject({ x: 50, y: 25 })
  })
  it('moves a node onto a new position that undo restores', async () => {
    const w = mountCanvas()
    await dragTo(nodeEl(w, 'a'), svgOf(w), [10, 10], [210, 110])
    await button(w, 'Undo').trigger('click')
    await nextTick()
    expect(x(w, 'a')).toMatchObject({ x: 0, y: 0 })
    expect(status(w)).toBe('Undid: Move Alpha.')
    await button(w, 'Redo').trigger('click')
    expect(x(w, 'a')).toMatchObject({ x: 200, y: 100 })
    expect(status(w)).toBe('Redid: Move Alpha.')
  })
  it('does not move anything when read only', async () => {
    const w = mountCanvas({ readonly: true })
    await dragTo(nodeEl(w, 'a'), svgOf(w), [10, 10], [210, 110])
    expect(x(w, 'a')).toMatchObject({ x: 0, y: 0 })
    expect(selected(w)).toEqual(['a'])
  })
  it('abandons a drag on pointercancel and on Escape', async () => {
    const w = mountCanvas()
    pointer(nodeEl(w, 'a'), 'pointerdown', { clientX: 10, clientY: 10 })
    pointer(svgOf(w), 'pointermove', { clientX: 110, clientY: 10 })
    pointer(svgOf(w), 'pointercancel', {})
    await nextTick()
    expect(x(w, 'a').x).toBe(0)
    expect(nodeEl(w, 'a').parentElement!.getAttribute('transform')).toBe('translate(0 0)')
    pointer(nodeEl(w, 'a'), 'pointerdown', { clientX: 10, clientY: 10 })
    pointer(svgOf(w), 'pointermove', { clientX: 110, clientY: 10 })
    viewport(w).element.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true }))
    pointer(svgOf(w), 'pointerup', { clientX: 110, clientY: 10 })
    await nextTick()
    expect(x(w, 'a').x).toBe(0)
    expect(w.emitted('node-move')).toBeUndefined()
  })
  it('keeps a node rounded to two decimals', async () => {
    const w = mountCanvas()
    setVp(w, { zoom: 0.3 })
    await nextTick()
    await dragTo(nodeEl(w, 'a'), svgOf(w), [10, 10], [11.111, 10], [13.337, 10])
    const v = x(w, 'a').x
    expect(Math.round(v * 100) / 100).toBe(v)
  })
})

describe('pan, zoom and pinch', () => {
  it('pans by dragging the background', async () => {
    const w = mountCanvas()
    await dragTo(svgOf(w), svgOf(w), [500, 300], [530, 340], [560, 360])
    expect(getVp(w)).toEqual({ x: 60, y: 60, zoom: 1 })
    expect(content(w)).toBe('translate(60 60) scale(1)')
    expect(viewport(w).attributes('data-panning')).toBeUndefined()
  })
  it('shows the grabbing cursor while panning', async () => {
    const w = mountCanvas()
    pointer(svgOf(w), 'pointerdown', { clientX: 500, clientY: 300 })
    await nextTick()
    expect(viewport(w).attributes('data-panning')).toBe('')
    expect(w.find('[data-slot="flow-canvas-svg"]').classes()).toContain('cursor-grabbing')
    pointer(svgOf(w), 'pointercancel', {})
    await nextTick()
    expect(viewport(w).attributes('data-panning')).toBeUndefined()
  })
  it('does not pan on a pointer cancel', async () => {
    const w = mountCanvas()
    pointer(svgOf(w), 'pointerdown', { clientX: 500, clientY: 300 })
    pointer(svgOf(w), 'pointermove', { clientX: 520, clientY: 300 })
    pointer(svgOf(w), 'pointercancel', {})
    expect(getVp(w).x).toBe(20)
  })
  it('zooms with ctrl or meta plus the wheel around the pointer and prevents page scroll', async () => {
    const w = mountCanvas()
    const e = new WheelEvent('wheel', { deltaY: -100, ctrlKey: true, clientX: 200, clientY: 100, bubbles: true, cancelable: true })
    svgOf(w).dispatchEvent(e)
    await nextTick()
    expect(e.defaultPrevented).toBe(true)
    const v = getVp(w)
    expect(v.zoom).toBeCloseTo(Math.exp(0.25), 5)
    expect((200 - v.x) / v.zoom).toBeCloseTo(200, 5)
    const m = new WheelEvent('wheel', { deltaY: 50, metaKey: true, deltaMode: 1, clientX: 0, clientY: 0, bubbles: true, cancelable: true })
    svgOf(w).dispatchEvent(m)
    expect(m.defaultPrevented).toBe(true)
    expect(getVp(w).zoom).toBeLessThan(v.zoom)
  })
  it('lets a plain wheel scroll the page', async () => {
    const w = mountCanvas()
    const e = new WheelEvent('wheel', { deltaY: 100, bubbles: true, cancelable: true })
    svgOf(w).dispatchEvent(e)
    expect(e.defaultPrevented).toBe(false)
    expect(getVp(w).zoom).toBe(1)
  })
  it('limits the wheel zoom', async () => {
    const w = mountCanvas({ maxZoom: 1.5 })
    svgOf(w).dispatchEvent(new WheelEvent('wheel', { deltaY: -5000, ctrlKey: true, bubbles: true, cancelable: true }))
    expect(getVp(w).zoom).toBe(1.5)
  })
  it('pinches with two pointers: zoom around the centre and follow the centre', async () => {
    const w = mountCanvas()
    pointer(svgOf(w), 'pointerdown', { pointerId: 1, pointerType: 'touch', clientX: 100, clientY: 100 })
    pointer(svgOf(w), 'pointerdown', { pointerId: 2, pointerType: 'touch', clientX: 200, clientY: 100 })
    pointer(svgOf(w), 'pointermove', { pointerId: 2, pointerType: 'touch', clientX: 300, clientY: 100 })
    await nextTick()
    const v = getVp(w)
    expect(v.zoom).toBeCloseTo(2, 5)
    // the canvas point under the original centre (150,100) is now under the new centre (200,100)
    expect((200 - v.x) / v.zoom).toBeCloseTo(150, 5)
    pointer(svgOf(w), 'pointermove', { pointerId: 2, pointerType: 'touch', clientX: 200, clientY: 100 })
    expect(getVp(w).zoom).toBe(1)
    pointer(svgOf(w), 'pointerup', { pointerId: 2, pointerType: 'touch', clientX: 100, clientY: 100 })
    // one finger left: no gesture, so it cannot jump the canvas
    pointer(svgOf(w), 'pointermove', { pointerId: 1, pointerType: 'touch', clientX: 400, clientY: 400 })
    const after = getVp(w)
    pointer(svgOf(w), 'pointermove', { pointerId: 1, pointerType: 'touch', clientX: 500, clientY: 500 })
    expect(getVp(w)).toEqual(after)
    pointer(svgOf(w), 'pointerup', { pointerId: 1, pointerType: 'touch' })
  })
  it('a second finger cancels a node drag and a connection, and a third finger is ignored', async () => {
    const w = mountCanvas()
    pointer(nodeEl(w, 'a'), 'pointerdown', { pointerId: 1, pointerType: 'touch', clientX: 10, clientY: 10 })
    pointer(svgOf(w), 'pointermove', { pointerId: 1, pointerType: 'touch', clientX: 80, clientY: 10 })
    pointer(svgOf(w), 'pointerdown', { pointerId: 2, pointerType: 'touch', clientX: 200, clientY: 200 })
    pointer(svgOf(w), 'pointerdown', { pointerId: 3, pointerType: 'touch', clientX: 300, clientY: 300 })
    pointer(svgOf(w), 'pointerup', { pointerId: 3, pointerType: 'touch' })
    pointer(svgOf(w), 'pointerup', { pointerId: 2, pointerType: 'touch' })
    pointer(svgOf(w), 'pointerup', { pointerId: 1, pointerType: 'touch' })
    await nextTick()
    expect(x(w, 'a').x).toBe(0)
    expect(w.emitted('node-move')).toBeUndefined()
    pointer(portEl(w, 'a', 'right'), 'pointerdown', { pointerId: 1, pointerType: 'touch', clientX: 148, clientY: 26 })
    pointer(svgOf(w), 'pointermove', { pointerId: 1, pointerType: 'touch', clientX: 200, clientY: 26 })
    await nextTick()
    expect(w.find('[data-slot="flow-canvas-link-preview"]').exists()).toBe(true)
    pointer(svgOf(w), 'pointerdown', { pointerId: 2, pointerType: 'touch', clientX: 300, clientY: 300 })
    await nextTick()
    expect(w.find('[data-slot="flow-canvas-link-preview"]').exists()).toBe(false)
    pointer(svgOf(w), 'pointerup', { pointerId: 2, pointerType: 'touch' })
    pointer(svgOf(w), 'pointerup', { pointerId: 1, pointerType: 'touch' })
  })
  it('uses touch-action none on the canvas and a select-none surface', () => {
    const w = mountCanvas()
    expect(viewport(w).classes()).toEqual(expect.arrayContaining(['touch-none', 'select-none', 'overflow-hidden']))
  })
})

