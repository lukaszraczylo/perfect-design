      const p = portEl(w, from[0], from[1])
      pointer(p, 'pointerdown', { clientX: 1, clientY: 1 })
      pointer(svgOf(w), 'pointermove', { clientX: to[0], clientY: to[1] })
      pointer(svgOf(w), 'pointerup', { clientX: to[0], clientY: to[1] })
