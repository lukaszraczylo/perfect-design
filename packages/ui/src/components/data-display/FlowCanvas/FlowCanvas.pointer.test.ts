describe('layout and viewport transform', () => {
  it('moves all nodes with the layered layout on autoLayout() and announces it', async () => {
    const w = mountCanvas({ nodes: [{ id: 'a', label: 'A', x: 0, y: 0 }, { id: 'b', label: 'B', x: 0, y: 0 }, { id: 'c', label: 'C', x: 0, y: 0 }], edges: [{ id: '1', from: 'a', to: 'b' }, { id: '2', from: 'b', to: 'c' }] })
    ;(w.vm as unknown as { autoLayout: () => void }).autoLayout()
    await flush()
    const xs = nodesProp(w).map((n) => n.x)
    expect(xs[0]).toBe(40)
    expect(xs[1]).toBeGreaterThan(xs[0]! + 148)
    expect(xs[2]).toBeGreaterThan(xs[1]! + 148)
    expect((w.emitted('node-move')!.at(-1)![0] as { nodes: unknown[] }).nodes).toHaveLength(3)
    expect(w.emitted('change')!.at(-1)![0]).toMatchObject({ reason: 'layout' })
    expect(status(w)).toBe('Arranged 3 nodes, left to right.')
    await button(w, 'Undo').trigger('click')
    expect(nodesProp(w).every((n) => n.x === 0)).toBe(true)
  })
  it('follows `direction` and the toolbar button; reports an empty canvas', async () => {
    const w = mountCanvas({ direction: 'TB', nodes: [{ id: 'a', x: 0, y: 0 }, { id: 'b', x: 0, y: 0 }], edges: [{ id: '1', from: 'a', to: 'b' }] })
    await button(w, 'Auto layout').trigger('click')
    expect(nodesProp(w)[1]!.y).toBeGreaterThan(nodesProp(w)[0]!.y + 52)
    expect(status(w)).toContain('top to bottom')
    const empty = mountCanvas({ nodes: [], edges: [] })
    ;(empty.vm as unknown as { autoLayout: () => void }).autoLayout()
    await nextTick()
    expect(status(empty)).toBe('There are no nodes to arrange.')
    expect(button(empty, 'Auto layout').attributes('disabled')).toBeDefined()
  })
  it('snaps the layout to the grid and emits nothing when nothing moves', async () => {
    const w = mountCanvas({ grid: 20, nodes: [{ id: 'a', x: 40, y: 40 }], edges: [] })
    ;(w.vm as unknown as { autoLayout: () => void }).autoLayout()
    await nextTick()
    expect(w.emitted('node-move')).toBeUndefined()
    expect(w.emitted('change')).toBeUndefined()
  })
  it('autoLayout still works when read only (the caller asked for it)', async () => {
    const w = mountCanvas({ readonly: true, nodes: [{ id: 'a', x: 5, y: 5 }, { id: 'b', x: 5, y: 5 }], edges: [{ id: '1', from: 'a', to: 'b' }] })
    ;(w.vm as unknown as { autoLayout: () => void }).autoLayout()
    await nextTick()
    expect(nodesProp(w)[1]!.x).toBeGreaterThan(100)
  })
})

