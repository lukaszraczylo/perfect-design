    await link(['a', 'right'], [350, 20]) // duplicate of e1 (no ports) is a different port pair: allowed
    expect(edgesProp(w)).toHaveLength(2)
    await link(['a', 'right'], [350, 20])
    expect(status(w)).toBe('Alpha is already connected to Beta.')
    expect(edgesProp(w)).toHaveLength(2)
    await link(['a', 'right'], [650, 20])
    expect(status(w)).toBe('Connection cancelled.')
    await link(['a', 'right'], [350, 220])
    expect(edgesProp(w)).toHaveLength(2)
    expect(w.emitted('connect')).toHaveLength(1)
