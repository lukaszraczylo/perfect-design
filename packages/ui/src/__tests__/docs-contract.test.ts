/**
 * Docs must describe the component that exists. For every documented component this compares the props table with the
 * component's real runtime props, so a renamed, removed or undocumented prop fails here instead of misleading a reader
 * (or an LLM generating code from llms.txt).
 */
import { describe, expect, it } from 'vitest'
import type { ComponentDoc } from '../docs-types'
import * as UI from '../index'

const docModules = import.meta.glob<{ default: ComponentDoc }>('../components/**/*.docs.ts', { eager: true })
const docs = Object.values(docModules).map((m) => m.default)

type WithProps = { props?: Record<string, unknown> | string[] }
function runtimeProps(component: unknown): string[] | null {
  const p = (component as WithProps)?.props
  if (!p) return null
  return Array.isArray(p) ? p : Object.keys(p)
}
// `xxxModifiers` props are generated by `v-model:xxx` and are not part of the public API.
const isModifier = (p: string) => p.endsWith('Modifiers')
const camel = (s: string) => s.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())

// Props that are intentionally forwarded rather than declared (documented as attributes), per component.
const ALLOW_UNDECLARED: Record<string, string[]> = {}
// Runtime props that are intentionally not documented (internal wiring), per component.
const ALLOW_UNDOCUMENTED: Record<string, string[]> = {}

describe('docs match runtime props', () => {
  it.each(docs.map((d) => [d.name, d] as const))('%s', (name, doc) => {
    const component = (UI as Record<string, unknown>)[name]
    expect(component, `${name} is exported`).toBeDefined()
    const real = runtimeProps(component)
    if (real === null) return // functional or attribute-only component: nothing to compare
    const documented = doc.props.map((p) => camel(p.name))
    const missingInCode = documented.filter((p) => p !== 'class' && !real.includes(p) && !(ALLOW_UNDECLARED[name] ?? []).includes(p))
    const missingInDocs = real.filter((p) => p !== 'class' && !isModifier(p) && !documented.includes(p) && !(ALLOW_UNDOCUMENTED[name] ?? []).includes(p))
    expect({ documentedButNotImplemented: missingInCode, implementedButNotDocumented: missingInDocs }).toEqual({
      documentedButNotImplemented: [],
      implementedButNotDocumented: [],
    })
  })
})

// Parts wrap reka-ui primitives that accept dozens of positioning props, so an undocumented part prop is allowed; a
// documented part prop that does not exist is not (it once told readers ContextMenuContent took `side` and `align`).
const parts = docs.flatMap((d) => (d.parts ?? []).filter((p) => p.props?.length).map((p) => [`${d.name} > ${p.name}`, p] as const))
describe('part docs match runtime props', () => {
  it.each(parts)('%s', (_label, part) => {
    const real = runtimeProps((UI as Record<string, unknown>)[part.name])
    if (real === null) return
    const missingInCode = part.props!.map((p) => camel(p.name)).filter((p) => p !== 'class' && !real.includes(p))
    expect({ documentedButNotImplemented: missingInCode }).toEqual({ documentedButNotImplemented: [] })
  })
})
