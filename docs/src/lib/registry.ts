import type { ComponentDoc } from '@ui/docs-types'
import nav from '@/generated/nav.json'

export const GROUP_ORDER = ['primitives', 'typography', 'layout', 'forms', 'feedback', 'overlays', 'navigation', 'data-display', 'marketing'] as const

export const GROUP_META: Record<string, { title: string; blurb: string }> = {
  primitives: { title: 'Primitives', blurb: 'Buttons, badges, avatars, progress and the smallest reusable building blocks.' },
  typography: { title: 'Typography', blurb: 'Headings, text, code and prose styling.' },
  layout: { title: 'Layout', blurb: 'Containers, stacks, grids, page headers and app shells.' },
  forms: { title: 'Forms', blurb: 'Every input control, field wrapper and form helper.' },
  feedback: { title: 'Feedback', blurb: 'Alerts, toasts, empty/error/loading states and confirmations.' },
  overlays: { title: 'Overlays', blurb: 'Dialogs, sheets, popovers, tooltips, menus and the command palette.' },
  navigation: { title: 'Navigation', blurb: 'Tabs, breadcrumbs, pagination, sidebars, headers and theme controls.' },
  'data-display': { title: 'Data display', blurb: 'Cards, tables, KPIs, lists, timelines, code and charts.' },
  marketing: { title: 'Marketing', blurb: 'Hero, feature grids, pricing, FAQ, footers and other site sections.' },
}

/** Lean per-component record generated by `pnpm generate:llms` (see scripts/generate-llms.ts). The full ComponentDoc is loaded lazily. */
export interface DocEntry {
  name: string
  slug: string
  group: string
  subgroup: string
  summary: string
  status: string
  /** Number of examples. */
  examples: number
  /** Number of compound parts. */
  parts: number
  replaces: string[]
  /** Repo-relative path of the docs file. */
  file: string
}

export function slugify(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase()
}

export function buildRegistry(list: DocEntry[]): DocEntry[] {
  const rank = (g: string) => {
    const i = (GROUP_ORDER as readonly string[]).indexOf(g)
    return i === -1 ? GROUP_ORDER.length : i
  }
  return list.toSorted((a, b) => rank(a.group) - rank(b.group) || a.subgroup.localeCompare(b.subgroup) || a.name.localeCompare(b.name))
}

export interface SubgroupNode { title: string; items: DocEntry[] }
export interface GroupNode { id: string; title: string; blurb: string; subgroups: SubgroupNode[]; count: number }

export function buildTree(list: DocEntry[]): GroupNode[] {
  const groups = new Map<string, GroupNode>()
  for (const e of list) {
    let g = groups.get(e.group)
    if (!g) {
      const meta = GROUP_META[e.group] ?? { title: e.group, blurb: '' }
      g = { id: e.group, ...meta, subgroups: [], count: 0 }
      groups.set(e.group, g)
    }
    let sg = g.subgroups.find((s) => s.title === e.subgroup)
    if (!sg) g.subgroups.push((sg = { title: e.subgroup, items: [] }))
    sg.items.push(e)
    g.count++
  }
  return [...groups.values()]
}

export const entries: DocEntry[] = buildRegistry(nav as DocEntry[])
export const tree: GroupNode[] = buildTree(entries)
export const findEntry = (group: string, slug: string) => entries.find((e) => e.group === group && e.slug === slug)

// Each docs file becomes its own lazy chunk: a component page only downloads the docs of the component being viewed.
const loaders = import.meta.glob<{ default: ComponentDoc }>('../../../packages/ui/src/components/**/*.docs.ts')
const docCache = new Map<string, ComponentDoc>()
/** Synchronous read of an already loaded doc (the router guard preloads it, so hydration renders the full page at once). */
export const cachedDoc = (entry: DocEntry): ComponentDoc | null => docCache.get(entry.file) ?? null
export async function loadDoc(entry: DocEntry): Promise<ComponentDoc | null> {
  const hit = docCache.get(entry.file)
  if (hit) return hit
  const loader = loaders[`../../../${entry.file}`]
  if (!loader) return null
  const doc = (await loader()).default
  docCache.set(entry.file, doc)
  return doc
}
