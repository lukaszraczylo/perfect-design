/**
 * Generates packages/ui/src/lib/icons.ts: the FontAwesome Free (solid) icons the library uses internally,
 * inlined as plain data so the library has NO runtime dependency on FontAwesome.
 * Re-run after adding an internal icon:  pnpm tsx scripts/gen-icons.ts
 * Icons: Font Awesome Free 7, https://fontawesome.com — CC BY 4.0 License.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const src = join(root, 'packages/ui/src')
const require = createRequire(join(root, 'packages/ui/package.json'))
const fa = require('@fortawesome/free-solid-svg-icons') as Record<string, { prefix: string; iconName: string; icon: unknown[] }>

function walk(dir: string, out: string[] = []) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n)
    if (statSync(p).isDirectory()) walk(p, out)
    else if (/\.(vue|ts)$/.test(n) && !/\.(test|docs)\.ts$/.test(n) && !p.endsWith('lib/icons.ts') && !p.includes('__tests__')) out.push(p)
  }
  return out
}

const names = new Set<string>()
for (const f of walk(src)) {
  const text = readFileSync(f, 'utf8')
  for (const m of text.matchAll(/import\s*\{([^}]+)\}\s*from\s*['"](?:@fortawesome\/free-solid-svg-icons|[./]+\/lib\/icons|@\/lib\/icons)['"]/g)) {
    for (const part of m[1].split(',')) {
      const n = part.trim().split(/\s+as\s+/)[0]
      if (/^fa[A-Z]/.test(n)) names.add(n)
    }
  }
}
const sorted = [...names].sort()
const missing = sorted.filter((n) => !fa[n])
if (missing.length) throw new Error(`Unknown FontAwesome icons: ${missing.join(', ')}`)

const body = sorted
  .map((n) => `export const ${n}: IconDefinition = { prefix: 'fas', iconName: '${fa[n].iconName}', icon: ${JSON.stringify(fa[n].icon)} }`)
  .join('\n')
writeFileSync(
  join(src, 'lib/icons.ts'),
  `// GENERATED by scripts/gen-icons.ts — do not edit by hand.\n// Font Awesome Free 7 (https://fontawesome.com), CC BY 4.0 License. Inlined so the library needs no FontAwesome runtime.\nimport type { IconDefinition } from './icons-tools'\n\n${body}\n`,
)
console.log(`Wrote ${sorted.length} icons.`)
